"""bevy_package — the Bevy package of a GLB (model.glb + af_bevy.json + fx_presets.json).

The fourth game-engine target of the Forge export (0.6.10 wave ticket 28, docs/forge/bevy.md):
the SAME model, rig and clips the Godot profile ships (a GLB goes out untouched - Bevy reads
glTF natively), plus an asset passport af_bevy.json that the astraforge_bevy crate consumes:
one dependency line in a user project gets the asset in-game with default-clip autostart, clip
blending, socket-mounted effects, studio sounds and hot reload.

inputs.glb       the asset (sockets per contract §6, clips '-loop' per §7) - as for godot_package
inputs.manifest  optional asset.json (kind, fx) - fx default from the passport of the asset
params:
  asset_id       snake_case ASCII (required, like the siblings)
  profile        'bevy' (the only one; the menu label names the Bevy version)
  collider       'auto' (collision hull meshes *-colonly/convcolonly/COL_* win, then rigged -
                 capsule, the rest - box) | box | capsule | mesh | none
  fx, fx_auto_scale, autoplay   as godot_package; '*' socket masks fan out over the real sockets
  validate       false by default here: the headless cargo check belongs to the engine driver
                 (ticket 30); the package builds identically without any Rust on the machine
outputs: package (folder), glb, manifest (af_bevy.json), readme
"""
import json
import os
import shutil

import bpy

import af_common as af
from steps import _bevy_lib as bl
from steps import _export_lib as xl
import steps.godot_package as gp   # _inspect - the same import-and-measure the Godot step uses


def _readme(pkg, passport):
    a = passport["asset_id"]
    lines = ["# %s - Bevy package" % a, "",
             "Generated by AstraForge (bevy_package). Drop this folder into your Bevy project's",
             "`assets/astraforge/%s/` (or let the studio send it) and add the crate:" % a, "",
             "```toml", "astraforge_bevy = \"0.20\"", "```", "",
             "```rust", "app.add_astraforge_asset(\"assets/astraforge/%s/af_bevy.json\");" % a, "```", "",
             "| File | What it is |", "| --- | --- |",
             "| `%s` | the model, rig and animations (glTF binary, y-up) |" % passport["glb"],
             "| `%s` | the passport: clips, default clip, sockets, collider, effects |" % bl.PASSPORT_FILE,
            ]
    if passport["fx_presets"]:
        lines.append("| `%s` | the effect presets the fx reference |" % passport["fx_presets"])
    lines += ["", "## What the crate does with it", "",
              "- autostarts `%s` on the spawned scene and blends between clips" % (passport["default_clip"] or "(no clips)"),
              "- mounts effect scenes at the %d socket(s) when an effect is requested" % len(passport["sockets"]),
              "- collider `%s`%s" % (passport["collider"]["kind"],
                                      (": hull meshes " + ", ".join(passport["collision_meshes"])) if passport["collider"]["kind"] == "hulls" else ""),
              "- watches the GLB and reloads the model in place on change", ""]
    clips = passport["clips"]
    if clips:
        lines += ["## Clips", "", "| name | loop | seconds |", "| --- | --- | --- |"]
        lines += ["| `%s` | %s | %.2f |" % (c["name"], "yes" if c["loop"] else "no", c["seconds"]) for c in clips]
        lines.append("")
    return "\n".join(lines)


def run(req):
    p = req["params"]
    inputs = req["inputs"]
    warnings, checks = [], []
    asset_id = p.get("asset_id")
    if not asset_id or not xl.ASSET_ID_RE.match(asset_id):
        raise ValueError("params.asset_id must be snake_case ASCII (^[a-z][a-z0-9]*(_[a-z0-9]+)*$): %r" % asset_id)
    glb = inputs.get("glb") or inputs.get("mesh")
    if not glb or not os.path.isfile(glb) or not glb.lower().endswith(".glb"):
        raise ValueError("bevy_package needs inputs.glb - the model, rig and clips (an existing .glb): %r" % glb)
    manifest = {}
    if inputs.get("manifest"):
        with open(inputs["manifest"], "r", encoding="utf-8-sig") as fh:
            manifest = json.load(fh)
    kind = manifest.get("kind") or p.get("kind")

    pkg_dir = af.out_path(req, asset_id)
    if os.path.isdir(pkg_dir):
        shutil.rmtree(pkg_dir)
    os.makedirs(pkg_dir)

    # measure the GLB the same way the Godot packer does, then count bones while the scene is in
    info = gp._inspect(glb)
    bones = sum(len(a.data.bones) for a in bpy.data.armatures)
    info["bones"] = bones
    names = [o.name for o in bpy.data.objects]
    collision = bl.collision_meshes(names)
    sockets = bl.socket_rows(info["sockets"])
    socket_names = [s["name"] for s in sockets]

    fx = bl.expand_fx(p.get("fx") or manifest.get("fx") or [], socket_names)
    presets_path = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", bl.FX_PRESETS_FILE))
    with open(presets_path, "r", encoding="utf-8") as fh:
        presets = (json.load(fh) or {}).get("presets") or {}
    unknown = bl.unknown_fx_presets(fx, presets)
    fx_copy = None
    if fx:
        fx_copy = bl.FX_PRESETS_FILE
        shutil.copyfile(presets_path, os.path.join(pkg_dir, bl.FX_PRESETS_FILE))

    shutil.copyfile(glb, os.path.join(pkg_dir, bl.GLB_FILE))
    clips = bl.glb_animations(os.path.join(pkg_dir, bl.GLB_FILE))   # the shipped bytes, not the re-import
    default_clip = bl.pick_default_clip(clips, p.get("autoplay"))
    rigged = bl.rig_summary(info)["type"] == "skinned"
    collider = bl.collider_plan(p.get("collider", "auto"), bool(collision), rigged)
    if p.get("collider", "auto") == "auto" and collision:
        # the hulls must not render as ordinary geometry either way - say what they are
        warnings.append("collision hulls kept as-is: they are excluded from rendering by the crate")

    passport = bl.build_passport(
        asset_id, info, clips=clips, default_clip=default_clip, sockets=sockets,
        collider=collider, collision=collision, fx=fx, fx_presets_file=fx_copy,
        rig=bl.rig_summary(info), kind=kind)

    # build checks: the passport must be true about the GLB it ships next to
    def chk(name, ok, value=None, limit=None, severity="error", note=None):
        c = af.check(name, ok, value, limit, severity=severity, note=note)
        checks.append(c)
        return c

    chk("glb_copied", os.path.getsize(os.path.join(pkg_dir, bl.GLB_FILE)) > 0,
        os.path.getsize(os.path.join(pkg_dir, bl.GLB_FILE)))
    chk("clips_found", bool(clips), len(clips), 1, severity="warning",
        note="a package without clips loads static; the passport says default_clip=\"\"")
    chk("default_clip_resolves", (not clips) or default_clip in [c["name"] for c in clips], default_clip)
    chk("sockets_unique", len(socket_names) == len(set(socket_names)), socket_names)
    fx_missing = sorted({f["socket"] for f in fx if f["socket"] and "*" not in f["socket"] and f["socket"] not in socket_names})
    chk("fx_sockets_exist", not fx_missing, fx_missing, [], severity="warning",
        note="an fx on a socket that is not in the model would never spawn")
    chk("fx_presets_known", not unknown, unknown, [], note="presets in data/fx_presets.json")
    chk("collider_kind_valid", collider["kind"] in ("none", "box", "capsule", "mesh", "hulls"), collider["kind"])
    chk("size_sane", 0.01 <= info["longest_m"] <= 100.0, info["longest_m"], [0.01, 100.0], severity="warning")
    passport["checks"] = [c["name"] for c in checks if c["ok"]]

    with open(os.path.join(pkg_dir, bl.PASSPORT_FILE), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(passport, fh, ensure_ascii=False, indent=1)
    with open(os.path.join(pkg_dir, "README.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(_readme(pkg_dir, passport))

    outputs = {"package": pkg_dir, "glb": os.path.join(pkg_dir, bl.GLB_FILE),
               "manifest": os.path.join(pkg_dir, bl.PASSPORT_FILE),
               "readme": os.path.join(pkg_dir, "README.md")}
    stats = {"tris": info["tris"], "clips": len(clips), "sockets": len(sockets), "fx": len(fx),
             "collider": collider["kind"], "default_clip": default_clip}
    return {"outputs": outputs, "stats": stats, "checks": checks, "warnings": warnings}
